"""Deterministic extractive test provider. This is not a language model."""

from cairn.adapters.protocol import Candidate, Job, Result
from cairn.policies.models import LEVEL
from cairn.records.models import Assertion, EvidenceRef, Processing, Record, canonical, digest


class FakeProvider:
    def generate(self, job: Job) -> Result:
        source = job.source
        refs = [
            EvidenceRef(
                id=source.id,
                source_hash=job.extraction.source_hash,
                evidence_hash=job.evidence_hash,
                locator=segment.locator,
                quote=segment.text[:1000],
            )
            for segment in job.extraction.segments[:5]
            if segment.text.strip()
        ]
        record_id = "concept_" + source.id.removeprefix("source_")
        inputs = [source, *(page.record for page in job.related)]
        classification = max((item.classification for item in inputs), key=LEVEL.__getitem__)
        processing: Processing = (
            "local_only"
            if any(item.processing == "local_only" for item in inputs)
            else "cloud_eligible"
        )
        compartments = set().union(*(item.compartments | {item.domain} for item in inputs))
        summary = Record(
            id=record_id,
            type="concept",
            title=f"Source summary: {source.title}",
            domain=source.domain,
            classification=classification,
            processing=processing,
            compartments=compartments - {source.domain},
            created_at=source.created_at,
            updated_at=source.updated_at,
            sources=refs,
            project_ids=source.project_ids,
            sections={"summary_of": source.id},
            assertions=[
                Assertion(
                    id=f"assertion_{index}_{record_id}",
                    text=f"Source reports: {ref.quote}",
                    kind="reported_result",
                    sources=[ref],
                )
                for index, ref in enumerate(refs)
            ],
        )
        body = "# Extractive demonstration\n\nGenerated by FakeProvider; owner review required.\n"
        body += "\n".join(f"\n> {ref.quote}\n\nEvidence: {ref.id}, {ref.locator}." for ref in refs)
        candidates = [
            Candidate(record=summary, body=body, rationale="Preserve quoted evidence for review.")
        ]
        for page in job.related:
            if len(candidates) >= job.max_changes:
                break
            if page.record.type != "project" or any(
                ref.id == source.id for ref in page.record.sources
            ):
                continue
            updated = page.record.model_copy(deep=True)
            updated.sources.extend(refs)
            updated.classification = classification
            updated.processing = processing
            updated.compartments = compartments - {updated.domain}
            updated.updated_at = max(updated.updated_at, source.updated_at)
            literature = updated.sections.get("relevant_literature", "")
            updated.sections["relevant_literature"] = f"{literature}\n{source.id}".strip()
            candidates.append(
                Candidate(
                    record=updated,
                    body=page.body,
                    rationale="Connect newly captured evidence to this project.",
                )
            )
        return Result(
            job_id=job.id,
            input_hash=digest(canonical(job)),
            provider="fake-v1",
            candidates=candidates,
            warnings=["Extractive fake output does not establish semantic correctness."],
        )
